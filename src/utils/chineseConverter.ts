/**
 * 將任意輸入字串轉換為 100% 台灣繁體中文 (正體中文)
 */
export function toTraditionalChinese(text: string): string {
  if (!text || typeof text !== 'string') return text;

  // 1. 先處理常用詞彙對照 (保留台灣地道用法)
  let result = text;
  for (const [regex, replacement] of TAIWAN_VOCABULARY_MAP) {
    result = result.replace(regex, replacement);
  }

  // 2. 逐字轉化簡體字至繁體字
  const charArray = Array.from(result);
  for (let i = 0; i < charArray.length; i++) {
    const char = charArray[i];
    if (S2T_CHAR_MAP[char]) {
      charArray[i] = S2T_CHAR_MAP[char];
    }
  }

  return charArray.join('');
}

/**
 * 深度遍歷並轉換物件內所有字串為繁體中文
 */
export function deepConvertObjectToTraditional<T>(obj: T): T {
  if (!obj) return obj;

  if (typeof obj === 'string') {
    return toTraditionalChinese(obj) as unknown as T;
  }

  if (Array.isArray(obj)) {
    return obj.map((item) => deepConvertObjectToTraditional(item)) as unknown as T;
  }

  if (typeof obj === 'object') {
    const converted: any = {};
    for (const [key, value] of Object.entries(obj)) {
      // 保持原始日文字、平假名與羅馬拼音不受影響
      if (key === 'japanese' || key === 'hiragana' || key === 'romaji' || key === 'originalText') {
        converted[key] = value;
      } else {
        converted[key] = deepConvertObjectToTraditional(value);
      }
    }
    return converted as T;
  }

  return obj;
}
